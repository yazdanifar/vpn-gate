#!/bin/bash
# Generates crates/vpngate-net/src/watermark.rs from SoftEther's WaterMark.c (Apache-2.0).
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=$(mktemp)
curl -sfL https://raw.githubusercontent.com/SoftEtherVPN/SoftEtherVPN/master/src/Cedar/WaterMark.c -o "$SRC"
python3 -I - "$SRC" > crates/vpngate-net/src/watermark.rs <<'PY'
import base64, re, sys
t = open(sys.argv[1]).read()
body = t[t.index("BYTE WaterMark[]"):]
body = body[body.index("{")+1: body.index("};")]
raw = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", body))
assert raw[:3] == b"GIF"
b64 = base64.b64encode(raw).decode()
print("//! SoftEther protocol signature image sent when opening a connection.")
print("// Generated by scripts/gen-watermark.sh from SoftEtherVPN src/Cedar/WaterMark.c")
print("// Copyright (c) SoftEther VPN Project, licensed under the Apache License 2.0.\n")
print("use base64::engine::general_purpose::STANDARD;")
print("use base64::Engine;\n")
print('const WATERMARK_BASE64: &str = "' + b64 + '";\n')
print("pub fn soft_ether_watermark() -> Vec<u8> {")
print('    STANDARD.decode(WATERMARK_BASE64).expect("embedded watermark is valid base64")')
print("}")
PY
rm -f "$SRC"
cargo fmt -p vpngate-net
